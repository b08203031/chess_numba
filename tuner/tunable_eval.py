@numba.njit(numba.types.UniTuple(numba.int32, 2)(piece_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_pawn_structure(piece_bbs, theta):
    mg_score = np.int32(0)
    eg_score = np.int32(0)
    
    white_pawns = piece_bbs[0]
    black_pawns = piece_bbs[6]
    white_king_sq = get_lsb_index(piece_bbs[5])
    black_king_sq = get_lsb_index(piece_bbs[11])

    # --- 1. Iterate White Pawns ---
    temp_wp = white_pawns
    while temp_wp:
        sq = get_lsb_index(temp_wp)
        rank = sq // 8
        file_idx = sq % 8

        # A. Passed Pawn Logic
        if not (WHITE_PASSED_PAWN_MASKS[sq] & black_pawns):
            mg_score += get_2d_val(theta, IDX_PASSED_PAWN_BONUS, rank, 2, 0)
            eg_score += get_2d_val(theta, IDX_PASSED_PAWN_BONUS, rank, 2, 1)

            # Connected Passed Pawn
            if (ADJACENT_FILES_MASKS[file_idx] & white_pawns):
                 mg_score += get_array_val(theta, IDX_CONNECTED_PASSED_PAWN_BONUS, 0)
                 eg_score += get_array_val(theta, IDX_CONNECTED_PASSED_PAWN_BONUS, 1)

            # King Proximity Logic
            if rank > 3: 
                block_sq = sq + 8 
                if block_sq < 64:
                    dist_friendly = MANHATTAN_DISTANCE[white_king_sq, block_sq]
                    dist_enemy = MANHATTAN_DISTANCE[black_king_sq, block_sq]
                    proximity_bonus = (dist_enemy * 5 - dist_friendly * 2) * rank
                    proximity_bonus = max(-150, min(150, proximity_bonus))
                    eg_score += proximity_bonus

        # B. Backward Pawn Logic
        else: 
             support_mask = WHITE_FORWARD_RANKS[sq] | RANK_MASKS[rank]
             adjacent_pawns = ADJACENT_FILES_MASKS[file_idx] & white_pawns
             has_support = (adjacent_pawns & support_mask) != 0

             if not has_support:
                 stop_sq = sq + 8
                 if stop_sq < 64:
                     if (PAWN_ATTACKS[1][stop_sq] & black_pawns):
                         mg_score -= get_array_val(theta, IDX_BACKWARD_PAWN_PENALTY, 0)
                         eg_score -= get_array_val(theta, IDX_BACKWARD_PAWN_PENALTY, 1)

        temp_wp &= temp_wp - np.uint64(1)

    # --- 2. Iterate Black Pawns ---
    temp_bp = black_pawns
    while temp_bp:
        sq = get_lsb_index(temp_bp)
        rank = sq // 8
        relative_rank = 7 - rank
        file_idx = sq % 8

        # A. Passed Pawn Logic
        if not (BLACK_PASSED_PAWN_MASKS[sq] & white_pawns):
            mg_score -= get_2d_val(theta, IDX_PASSED_PAWN_BONUS, relative_rank, 2, 0)
            eg_score -= get_2d_val(theta, IDX_PASSED_PAWN_BONUS, relative_rank, 2, 1)

            if (ADJACENT_FILES_MASKS[file_idx] & black_pawns):
                 mg_score -= get_array_val(theta, IDX_CONNECTED_PASSED_PAWN_BONUS, 0)
                 eg_score -= get_array_val(theta, IDX_CONNECTED_PASSED_PAWN_BONUS, 1)

            if relative_rank > 3:
                block_sq = sq - 8
                if block_sq >= 0:
                    dist_friendly = MANHATTAN_DISTANCE[black_king_sq, block_sq]
                    dist_enemy = MANHATTAN_DISTANCE[white_king_sq, block_sq]
                    proximity_bonus = (dist_enemy * 5 - dist_friendly * 2) * relative_rank
                    proximity_bonus = max(-150, min(150, proximity_bonus))
                    eg_score -= proximity_bonus

        # B. Backward Pawn Logic
        else:
             support_mask = BLACK_FORWARD_RANKS[sq] | RANK_MASKS[rank]
             adjacent_pawns = ADJACENT_FILES_MASKS[file_idx] & black_pawns
             has_support = (adjacent_pawns & support_mask) != 0

             if not has_support:
                 stop_sq = sq - 8
                 if stop_sq >= 0:
                     if (PAWN_ATTACKS[0][stop_sq] & white_pawns):
                         mg_score += get_array_val(theta, IDX_BACKWARD_PAWN_PENALTY, 0)
                         eg_score += get_array_val(theta, IDX_BACKWARD_PAWN_PENALTY, 1)

        temp_bp &= temp_bp - np.uint64(1)

    # --- 3. Isolated / Doubled ---
    iso_mg = get_array_val(theta, IDX_ISOLATED_PAWN_PENALTY, 0)
    iso_eg = get_array_val(theta, IDX_ISOLATED_PAWN_PENALTY, 1)
    dbl_mg = get_array_val(theta, IDX_DOUBLED_PAWN_PENALTY, 0)
    dbl_eg = get_array_val(theta, IDX_DOUBLED_PAWN_PENALTY, 1)

    for f in range(8):
        file_mask = FILE_MASKS[f]
        adjacent_mask = ADJACENT_FILES_MASKS[f]

        white_pawns_on_file = count_bits(white_pawns & file_mask)
        black_pawns_on_file = count_bits(black_pawns & file_mask)

        # White
        if white_pawns_on_file > 0:
            if not (white_pawns & adjacent_mask):
                mg_score += iso_mg * white_pawns_on_file
                eg_score += iso_eg * white_pawns_on_file
            if white_pawns_on_file > 1:
                mg_score += dbl_mg * (white_pawns_on_file - 1)
                eg_score += dbl_eg * (white_pawns_on_file - 1)

        # Black
        if black_pawns_on_file > 0:
            if not (black_pawns & adjacent_mask):
                mg_score -= iso_mg * black_pawns_on_file
                eg_score -= iso_eg * black_pawns_on_file
            if black_pawns_on_file > 1:
                mg_score -= dbl_mg * (black_pawns_on_file - 1)
                eg_score -= dbl_eg * (black_pawns_on_file - 1)

    return mg_score, eg_score

@numba.njit(numba.types.UniTuple(numba.int32, 2)(piece_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_piece_coordination(piece_bbs, theta):
    mg_score = np.int32(0)
    eg_score = np.int32(0)

    white_pawns = piece_bbs[0]
    white_bishops = piece_bbs[2]
    white_rooks = piece_bbs[3]
    black_pawns = piece_bbs[6]
    black_bishops = piece_bbs[8]
    black_rooks = piece_bbs[9]
    
    bp_mg = get_array_val(theta, IDX_BISHOP_PAIR_BONUS, 0)
    bp_eg = get_array_val(theta, IDX_BISHOP_PAIR_BONUS, 1)

    if count_bits(white_bishops) >= 2:
        mg_score += bp_mg
        eg_score += bp_eg
    if count_bits(black_bishops) >= 2:
        mg_score -= bp_mg
        eg_score -= bp_eg

    open_mg = get_array_val(theta, IDX_ROOK_ON_OPEN_FILE_BONUS, 0)
    open_eg = get_array_val(theta, IDX_ROOK_ON_OPEN_FILE_BONUS, 1)
    semi_mg = get_array_val(theta, IDX_ROOK_ON_SEMI_OPEN_FILE_BONUS, 0)
    semi_eg = get_array_val(theta, IDX_ROOK_ON_SEMI_OPEN_FILE_BONUS, 1)

    for f in range(8):
        file_mask = FILE_MASKS[f]
        white_pawns_on_file = (white_pawns & file_mask) != 0
        black_pawns_on_file = (black_pawns & file_mask) != 0

        if (white_rooks & file_mask):
            if not white_pawns_on_file:
                if not black_pawns_on_file:
                    mg_score += open_mg
                    eg_score += open_eg
                else:
                    mg_score += semi_mg
                    eg_score += semi_eg
        
        if (black_rooks & file_mask):
            if not black_pawns_on_file:
                if not white_pawns_on_file:
                    mg_score -= open_mg
                    eg_score -= open_eg
                else:
                    mg_score -= semi_mg
                    eg_score -= semi_eg
                    
    # Rook on 7th
    r7_mg = get_array_val(theta, IDX_ROOK_ON_SEVENTH_BONUS, 0)
    r7_eg = get_array_val(theta, IDX_ROOK_ON_SEVENTH_BONUS, 1)
    
    white_rooks_on_7th = white_rooks & RANK_MASKS[6]
    if white_rooks_on_7th:
        count = count_bits(white_rooks_on_7th)
        mg_score += r7_mg * count
        eg_score += r7_eg * count

    black_rooks_on_7th = black_rooks & RANK_MASKS[1]
    if black_rooks_on_7th:
        count = count_bits(black_rooks_on_7th)
        mg_score -= r7_mg * count
        eg_score -= r7_eg * count

    return mg_score, eg_score

@numba.njit(numba.int32(numba.int32, numba.uint64, numba.uint64, numba.int32, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def _evaluate_pawn_shield_for_color(king_sq, friendly_pawns, enemy_pawns, color, theta):
    score = np.int32(0)
    king_file = king_sq % 8
    original_rank = 1 if color == 0 else 6
    one_step_rank = 2 if color == 0 else 5
    
    shield_missing = get_int(theta, IDX_PAWN_SHIELD_MISSING_PENALTY)
    shield_intact = get_int(theta, IDX_PAWN_SHIELD_INTACT_BONUS)
    shield_advanced = get_int(theta, IDX_PAWN_SHIELD_ADVANCED_BONUS)
    shield_pushed = get_int(theta, IDX_PAWN_SHIELD_PUSHED_PENALTY)
    open_file = get_int(theta, IDX_KING_OPEN_FILE_PENALTY)
    semi_open_file = get_int(theta, IDX_KING_SEMI_OPEN_FILE_PENALTY)

    for f in range(max(0, king_file - 1), min(7, king_file + 1) + 1):
        file_mask = FILE_MASKS[f]
        pawns_on_file = friendly_pawns & file_mask
        if not pawns_on_file:
            score -= shield_missing
        else:
            pawn_sq = get_lsb_index(pawns_on_file)
            pawn_rank = pawn_sq // 8
            if pawn_rank == original_rank:
                score += shield_intact
            elif pawn_rank == one_step_rank:
                score += shield_advanced
            else:
                score -= shield_pushed
        if not (friendly_pawns & file_mask):
            if not (enemy_pawns & file_mask):
                score -= open_file
            else:
                score -= semi_open_file
    return score

@numba.njit(numba.int32(numba.int32, numba.int32, piece_bbs_signature, occupancy_bbs_signature, numba.uint64, numba.uint64, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def _evaluate_king_attackers(king_sq, color, piece_bbs, occupancy_bbs, enemy_attacks_bb, friendly_attacks_bb, theta):
    king_zone = KING_ATTACK_ZONES[king_sq]
    total_attack_units = np.int32(0)
    attacker_count = np.int32(0)

    enemy_start_idx = 6 if color == 0 else 0
    (en_p, en_n, en_b, en_r, en_q, _) = piece_bbs[enemy_start_idx : enemy_start_idx + 6]
    all_pieces_occupancy = occupancy_bbs[2]
    
    # Attack Units: P, N, B, R, Q
    u_p = get_array_val(theta, IDX_KING_SAFETY_ATTACK_UNITS, 0)
    u_n = get_array_val(theta, IDX_KING_SAFETY_ATTACK_UNITS, 1)
    u_b = get_array_val(theta, IDX_KING_SAFETY_ATTACK_UNITS, 2)
    u_r = get_array_val(theta, IDX_KING_SAFETY_ATTACK_UNITS, 3)
    u_q = get_array_val(theta, IDX_KING_SAFETY_ATTACK_UNITS, 4)

    # Pawns Logic Restored
    pawn_attack_sources_bb = np.uint64(0)
    temp_king_zone = king_zone
    while temp_king_zone:
        zone_sq = get_lsb_index(temp_king_zone)
        pawn_attack_sources_bb |= PAWN_ATTACKS[color, zone_sq]
        temp_king_zone &= temp_king_zone - np.uint64(1)

    actual_pawn_attackers = pawn_attack_sources_bb & en_p
    if actual_pawn_attackers:
        num = count_bits(actual_pawn_attackers)
        total_attack_units += num * u_p
        attacker_count += num

    # Knights
    temp_bb = en_n
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        if KNIGHT_ATTACKS[sq] & king_zone:
            total_attack_units += u_n
            attacker_count += 1
        temp_bb &= temp_bb - np.uint64(1)
        
    # Bishops
    temp_bb = en_b
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        attacks = get_bishop_attacks(sq, all_pieces_occupancy & ~BB_SQUARES[sq])
        if attacks & king_zone:
            total_attack_units += u_b
            attacker_count += 1
        temp_bb &= temp_bb - np.uint64(1)
        
    # Rooks
    temp_bb = en_r
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        attacks = get_rook_attacks(sq, all_pieces_occupancy & ~BB_SQUARES[sq])
        if attacks & king_zone:
            total_attack_units += u_r
            attacker_count += 1
        temp_bb &= temp_bb - np.uint64(1)
        
    # Queens
    temp_bb = en_q
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        attacks = get_queen_attacks(sq, all_pieces_occupancy & ~BB_SQUARES[sq])
        if attacks & king_zone:
            total_attack_units += u_q
            attacker_count += 1
        temp_bb &= temp_bb - np.uint64(1)

    # Weak Squares
    undefended_in_zone = (king_zone & enemy_attacks_bb) & ~friendly_attacks_bb
    weak_count = count_bits(undefended_in_zone)
    weak_penalty_val = get_int(theta, IDX_KING_SAFETY_WEAK_SQUARE_PENALTY)
    weak_penalty = weak_count * weak_penalty_val
    total_attack_units += weak_penalty

    if attacker_count < 2 and weak_count == 0:
        return np.int32(0)

    # Lookup table logic
    idx = min(total_attack_units, 99)
    return -get_array_val(theta, IDX_KING_SAFETY_TABLE, idx)

@numba.njit(numba.int32(numba.int32, numba.int32, piece_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def _evaluate_king_tropism(king_sq, color, piece_bbs, theta):
    penalty = np.int32(0)
    enemy_start_idx = 6 if color == 0 else 0

    for piece_type_offset in range(5): # P, N, B, R, Q
        piece_type = enemy_start_idx + piece_type_offset
        weight = get_array_val(theta, IDX_KING_TROPISM_WEIGHTS, piece_type_offset)

        temp_bb = piece_bbs[piece_type]
        while temp_bb:
            sq = get_lsb_index(temp_bb)
            distance = MANHATTAN_DISTANCE[sq, king_sq]
            penalty += weight * (KING_TROPISM_MAX_DISTANCE - distance)
            temp_bb &= temp_bb - np.uint64(1)

    return -penalty

@numba.njit(numba.int32(numba.int32, numba.int32, piece_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def _evaluate_pawn_storm(king_sq, color, piece_bbs, theta):
    penalty = np.int32(0)
    king_file = king_sq % 8
    enemy_pawn_idx = 6 if color == 0 else 0
    enemy_pawns = piece_bbs[enemy_pawn_idx]

    for f in range(max(0, king_file - 1), min(7, king_file + 1) + 1):
        file_mask = FILE_MASKS[f]
        pawns_on_file = enemy_pawns & file_mask
        while pawns_on_file:
            sq = get_lsb_index(pawns_on_file)
            rank = sq // 8
            table_idx = rank if color == 0 else (7 - rank)
            penalty -= get_array_val(theta, IDX_PAWN_STORM_PENALTY_BY_RANK, table_idx)
            pawns_on_file &= pawns_on_file - np.uint64(1)
    return penalty

@numba.njit(numba.types.UniTuple(numba.int32, 2)(piece_bbs_signature, occupancy_bbs_signature, numba.uint64, numba.uint64, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_king_safety(piece_bbs, occupancy_bbs, white_attacks, black_attacks, theta):
    (wp_bb, wn_bb, wb_bb, wr_bb, wq_bb, wk_bb,
    bp_bb, bn_bb, bb_bb, br_bb, bq_bb, bk_bb) = piece_bbs
    white_king_sq = get_lsb_index(wk_bb)
    black_king_sq = get_lsb_index(bk_bb)

    # Raw
    white_shield = _evaluate_pawn_shield_for_color(white_king_sq, wp_bb, bp_bb, 0, theta)
    white_attackers = _evaluate_king_attackers(white_king_sq, 0, piece_bbs, occupancy_bbs, black_attacks, white_attacks, theta)
    white_tropism = _evaluate_king_tropism(white_king_sq, 0, piece_bbs, theta)
    white_pawn_storm = _evaluate_pawn_storm(white_king_sq, 0, piece_bbs, theta)

    black_shield = _evaluate_pawn_shield_for_color(black_king_sq, bp_bb, wp_bb, 1, theta)
    black_attackers = _evaluate_king_attackers(black_king_sq, 1, piece_bbs, occupancy_bbs, white_attacks, black_attacks, theta)
    black_tropism = _evaluate_king_tropism(black_king_sq, 1, piece_bbs, theta)
    black_pawn_storm = _evaluate_pawn_storm(black_king_sq, 1, piece_bbs, theta)

    white_raw = white_shield + white_attackers + white_tropism + white_pawn_storm
    black_raw = black_shield + black_attackers + black_tropism + black_pawn_storm

    # Scaling
    w_n = get_array_val(theta, IDX_SCALING_WEIGHTS, 1)
    w_b = get_array_val(theta, IDX_SCALING_WEIGHTS, 2)
    w_r = get_array_val(theta, IDX_SCALING_WEIGHTS, 3)
    w_q = get_array_val(theta, IDX_SCALING_WEIGHTS, 4)

    black_mat = (count_bits(bn_bb)*w_n + count_bits(bb_bb)*w_b + count_bits(br_bb)*w_r + count_bits(bq_bb)*w_q)
    white_scale = black_mat / MAX_SCALING_MATERIAL
    white_final = np.int32(white_raw * white_scale)

    white_mat = (count_bits(wn_bb)*w_n + count_bits(wb_bb)*w_b + count_bits(wr_bb)*w_r + count_bits(wq_bb)*w_q)
    black_scale = white_mat / MAX_SCALING_MATERIAL
    black_final = np.int32(black_raw * black_scale)

    mg_score = white_final - black_final
    eg_score = mg_score * EG_SAFETY_SCALE
    return mg_score, eg_score

@numba.njit(numba.types.UniTuple(numba.int32, 2)(piece_bbs_signature, occupancy_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_mobility(piece_bbs, occupancy_bbs, theta):
    mg_score = np.int32(0)
    eg_score = np.int32(0)
    white_occupancy = occupancy_bbs[0]
    black_occupancy = occupancy_bbs[1]
    all_pieces_occupancy = occupancy_bbs[2]

    # Param helpers
    def get_mob_params(idx_weight):
        return get_array_val(theta, idx_weight, 0), get_array_val(theta, idx_weight, 1)

    n_w_mg, n_w_eg = get_mob_params(IDX_KNIGHT_MOBILITY_WEIGHT)
    b_w_mg, b_w_eg = get_mob_params(IDX_BISHOP_MOBILITY_WEIGHT)
    r_w_mg, r_w_eg = get_mob_params(IDX_ROOK_MOBILITY_WEIGHT)
    q_w_mg, q_w_eg = get_mob_params(IDX_QUEEN_MOBILITY_WEIGHT)

    # Calculate Forbidden Zones for Safe Mobility (match evaluation.py)
    white_pawn_attacks = ((piece_bbs[0] & NOT_A_FILE) << np.uint64(7)) | \
                         ((piece_bbs[0] & NOT_H_FILE) << np.uint64(9))
    black_pawn_attacks = ((piece_bbs[6] & NOT_H_FILE) >> np.uint64(7)) | \
                         ((piece_bbs[6] & NOT_A_FILE) >> np.uint64(9))
                         
    white_forbidden = black_pawn_attacks | piece_bbs[5] | piece_bbs[4]
    black_forbidden = white_pawn_attacks | piece_bbs[11] | piece_bbs[10]

    white_safe_mask = ~white_forbidden
    black_safe_mask = ~black_forbidden

    # White
    temp_bb = piece_bbs[1]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(KNIGHT_ATTACKS[sq] & ~white_occupancy & white_safe_mask)
        mg_score += (moves - KNIGHT_MOBILITY_BASE_MOVES) * n_w_mg
        eg_score += (moves - KNIGHT_MOBILITY_BASE_MOVES) * n_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[2]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_bishop_attacks(sq, all_pieces_occupancy) & ~white_occupancy & white_safe_mask)
        mg_score += (moves - BISHOP_MOBILITY_BASE_MOVES) * b_w_mg
        eg_score += (moves - BISHOP_MOBILITY_BASE_MOVES) * b_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[3]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_rook_attacks(sq, all_pieces_occupancy) & ~white_occupancy & white_safe_mask)
        mg_score += (moves - ROOK_MOBILITY_BASE_MOVES) * r_w_mg
        eg_score += (moves - ROOK_MOBILITY_BASE_MOVES) * r_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[4]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_queen_attacks(sq, all_pieces_occupancy) & ~white_occupancy & white_safe_mask)
        mg_score += (moves - QUEEN_MOBILITY_BASE_MOVES) * q_w_mg
        eg_score += (moves - QUEEN_MOBILITY_BASE_MOVES) * q_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    # Black (Subtract)
    temp_bb = piece_bbs[7]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(KNIGHT_ATTACKS[sq] & ~black_occupancy & black_safe_mask)
        mg_score -= (moves - KNIGHT_MOBILITY_BASE_MOVES) * n_w_mg
        eg_score -= (moves - KNIGHT_MOBILITY_BASE_MOVES) * n_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[8]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_bishop_attacks(sq, all_pieces_occupancy) & ~black_occupancy & black_safe_mask)
        mg_score -= (moves - BISHOP_MOBILITY_BASE_MOVES) * b_w_mg
        eg_score -= (moves - BISHOP_MOBILITY_BASE_MOVES) * b_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[9]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_rook_attacks(sq, all_pieces_occupancy) & ~black_occupancy & black_safe_mask)
        mg_score -= (moves - ROOK_MOBILITY_BASE_MOVES) * r_w_mg
        eg_score -= (moves - ROOK_MOBILITY_BASE_MOVES) * r_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = piece_bbs[10]
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        moves = count_bits(get_queen_attacks(sq, all_pieces_occupancy) & ~black_occupancy & black_safe_mask)
        mg_score -= (moves - QUEEN_MOBILITY_BASE_MOVES) * q_w_mg
        eg_score -= (moves - QUEEN_MOBILITY_BASE_MOVES) * q_w_eg
        temp_bb &= temp_bb - np.uint64(1)

    return mg_score, eg_score

@numba.njit(numba.types.UniTuple(numba.int32, 2)(piece_bbs_signature, occupancy_bbs_signature, numba.uint64, numba.uint64, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_threats(piece_bbs, occupancy_bbs, white_attacks, black_attacks, theta):
    mg_score = np.int32(0)
    eg_score = np.int32(0)

    (wp_bb, wn_bb, wb_bb, wr_bb, wq_bb, _,
     bp_bb, bn_bb, bb_bb, br_bb, bq_bb, _) = piece_bbs
    all_occupancy = occupancy_bbs[2]

    # --- Params ---
    safe_pawn_mg = get_array_val(theta, IDX_THREAT_SAFE_PAWN, 0)
    safe_pawn_eg = get_array_val(theta, IDX_THREAT_SAFE_PAWN, 1)
    
    hanging_mg = get_array_val(theta, IDX_THREAT_HANGING, 0)
    hanging_eg = get_array_val(theta, IDX_THREAT_HANGING, 1)
    
    minor_major_mg = get_array_val(theta, IDX_THREAT_MINOR_ON_MAJOR, 0)
    minor_major_eg = get_array_val(theta, IDX_THREAT_MINOR_ON_MAJOR, 1)
    
    rook_queen_mg = get_array_val(theta, IDX_THREAT_ROOK_ON_QUEEN, 0)
    rook_queen_eg = get_array_val(theta, IDX_THREAT_ROOK_ON_QUEEN, 1)

    # --- 1. Safe Pawn Threats ---
    white_pawn_attacks = ((wp_bb & NOT_A_FILE) << np.uint64(7)) | \
                         ((wp_bb & NOT_H_FILE) << np.uint64(9))
    black_pawn_attacks = ((bp_bb & NOT_H_FILE) >> np.uint64(7)) | \
                         ((bp_bb & NOT_A_FILE) >> np.uint64(9))

    black_non_pawns = bn_bb | bb_bb | br_bb | bq_bb
    white_non_pawns = wn_bb | wb_bb | wr_bb | wq_bb

    white_safe_pawn_threats = white_pawn_attacks & black_non_pawns
    if white_safe_pawn_threats:
        count = count_bits(white_safe_pawn_threats)
        mg_score += safe_pawn_mg * count
        eg_score += safe_pawn_eg * count

    black_safe_pawn_threats = black_pawn_attacks & white_non_pawns
    if black_safe_pawn_threats:
        count = count_bits(black_safe_pawn_threats)
        mg_score -= safe_pawn_mg * count
        eg_score -= safe_pawn_eg * count

    # --- 2. Hanging Pieces ---
    all_black_pieces = bp_bb | bn_bb | bb_bb | br_bb | bq_bb
    black_hanging_mask = (all_black_pieces & white_attacks) & ~black_attacks
    if black_hanging_mask:
        count = count_bits(black_hanging_mask)
        mg_score += hanging_mg * count
        eg_score += hanging_eg * count

    all_white_pieces = wp_bb | wn_bb | wb_bb | wr_bb | wq_bb
    white_hanging_mask = (all_white_pieces & black_attacks) & ~white_attacks
    if white_hanging_mask:
        count = count_bits(white_hanging_mask)
        mg_score -= hanging_mg * count
        eg_score -= hanging_eg * count

    # --- 3. Minor on Major ---
    # White minor attacks
    temp_bb = wn_bb
    white_knight_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        white_knight_attacks |= KNIGHT_ATTACKS[sq]
        temp_bb &= temp_bb - np.uint64(1)
    
    temp_bb = wb_bb
    white_bishop_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        white_bishop_attacks |= get_bishop_attacks(sq, all_occupancy)
        temp_bb &= temp_bb - np.uint64(1)

    white_minor_attacks = white_knight_attacks | white_bishop_attacks
    black_majors = br_bb | bq_bb
    
    threats = white_minor_attacks & black_majors
    if threats:
        count = count_bits(threats)
        mg_score += minor_major_mg * count
        eg_score += minor_major_eg * count

    # Black minor attacks
    temp_bb = bn_bb
    black_knight_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        black_knight_attacks |= KNIGHT_ATTACKS[sq]
        temp_bb &= temp_bb - np.uint64(1)

    temp_bb = bb_bb
    black_bishop_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        black_bishop_attacks |= get_bishop_attacks(sq, all_occupancy)
        temp_bb &= temp_bb - np.uint64(1)

    black_minor_attacks = black_knight_attacks | black_bishop_attacks
    white_majors = wr_bb | wq_bb
    
    threats = black_minor_attacks & white_majors
    if threats:
        count = count_bits(threats)
        mg_score -= minor_major_mg * count
        eg_score -= minor_major_eg * count

    # --- 4. Rook on Queen ---
    # White
    temp_bb = wr_bb
    white_rook_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        white_rook_attacks |= get_rook_attacks(sq, all_occupancy)
        temp_bb &= temp_bb - np.uint64(1)
    
    if white_rook_attacks & bq_bb:
        count = count_bits(white_rook_attacks & bq_bb)
        mg_score += rook_queen_mg * count
        eg_score += rook_queen_eg * count
        
    # Black
    temp_bb = br_bb
    black_rook_attacks = np.uint64(0)
    while temp_bb:
        sq = get_lsb_index(temp_bb)
        black_rook_attacks |= get_rook_attacks(sq, all_occupancy)
        temp_bb &= temp_bb - np.uint64(1)
        
    if black_rook_attacks & wq_bb:
        count = count_bits(black_rook_attacks & wq_bb)
        mg_score -= rook_queen_mg * count
        eg_score -= rook_queen_eg * count

    return mg_score, eg_score

@numba.njit(numba.int32(piece_bbs_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def _evaluate_king_pawn_endgame(piece_bbs, theta):
    score = np.int32(0)
    white_pawns = piece_bbs[0]
    white_king_sq = get_lsb_index(piece_bbs[5])
    black_pawns = piece_bbs[6]
    black_king_sq = get_lsb_index(piece_bbs[11])
    
    # Values
    eg_pawn_val = get_array_val(theta, IDX_EG_MATERIAL_VALUES, 0)
    
    # White
    temp_wp = white_pawns
    while temp_wp:
        sq = get_lsb_index(temp_wp)
        score += eg_pawn_val + get_2d_val(theta, IDX_PST_EG, 0, 64, sq)
        temp_wp &= temp_wp - np.uint64(1)
        
    # Black
    temp_bp = black_pawns
    while temp_bp:
        sq = get_lsb_index(temp_bp)
        score -= (eg_pawn_val + get_2d_val(theta, IDX_PST_EG, 0, 64, sq^56))
        temp_bp &= temp_bp - np.uint64(1)
        
    score += get_2d_val(theta, IDX_PST_EG, 5, 64, white_king_sq)
    score -= get_2d_val(theta, IDX_PST_EG, 5, 64, black_king_sq^56)
    
    _, eg_struct = evaluate_pawn_structure(piece_bbs, theta)
    score += eg_struct
    
    # Proximity
    temp_pawns = white_pawns | black_pawns
    while temp_pawns:
        sq = get_lsb_index(temp_pawns)
        score += (KING_TROPISM_MAX_DISTANCE - MANHATTAN_DISTANCE[white_king_sq, sq]) * 5
        temp_pawns &= temp_pawns - np.uint64(1)
        
    temp_pawns = white_pawns | black_pawns
    while temp_pawns:
        sq = get_lsb_index(temp_pawns)
        score -= (KING_TROPISM_MAX_DISTANCE - MANHATTAN_DISTANCE[black_king_sq, sq]) * 5
        temp_pawns &= temp_pawns - np.uint64(1)
        
    return score

@numba.njit(numba.int32(piece_bbs_signature, occupancy_bbs_signature, game_state_signature, numba.float64[:]), cache=True, boundscheck=False, fastmath=True)
def evaluate_position_tunable(piece_bbs, occupancy_bbs, game_state, theta):
    # King Pawn Endgame
    all_pieces_except_pawns_and_kings = (
        piece_bbs[1] | piece_bbs[2] | piece_bbs[3] | piece_bbs[4] |
        piece_bbs[7] | piece_bbs[8] | piece_bbs[9] | piece_bbs[10]
    )
    if all_pieces_except_pawns_and_kings == 0:
        score = _evaluate_king_pawn_endgame(piece_bbs, theta)
        return score if game_state[0] == 0 else -score
    
    side_to_move = game_state[0]
    
    # Phase
    phase = np.int32(0)
    phase += count_bits(piece_bbs[1]) * PHASE_WEIGHTS[1]
    phase += count_bits(piece_bbs[2]) * PHASE_WEIGHTS[2]
    phase += count_bits(piece_bbs[3]) * PHASE_WEIGHTS[3]
    phase += count_bits(piece_bbs[4]) * PHASE_WEIGHTS[4]
    phase += count_bits(piece_bbs[7]) * PHASE_WEIGHTS[1]
    phase += count_bits(piece_bbs[8]) * PHASE_WEIGHTS[2]
    phase += count_bits(piece_bbs[9]) * PHASE_WEIGHTS[3]
    phase += count_bits(piece_bbs[10]) * PHASE_WEIGHTS[4]
    phase = min(phase, MAX_PHASE)
    
    mg_score = np.int32(0)
    eg_score = np.int32(0)
    
    # Material
    for pt in range(6):
        cnt_w = count_bits(piece_bbs[pt])
        cnt_b = count_bits(piece_bbs[pt+6])
        val_mg = get_array_val(theta, IDX_MG_MATERIAL_VALUES, pt)
        val_eg = get_array_val(theta, IDX_EG_MATERIAL_VALUES, pt)
        
        mg_score += (cnt_w - cnt_b) * val_mg
        eg_score += (cnt_w - cnt_b) * val_eg
        
    # PST
    for pt in range(6):
        # White
        bb = piece_bbs[pt]
        while bb:
            sq = get_lsb_index(bb)
            mg_score += get_2d_val(theta, IDX_PST_MG, pt, 64, sq)
            eg_score += get_2d_val(theta, IDX_PST_EG, pt, 64, sq)
            bb &= bb - np.uint64(1)
        # Black
        bb = piece_bbs[pt+6]
        while bb:
            sq = get_lsb_index(bb)
            mg_score -= get_2d_val(theta, IDX_PST_MG, pt, 64, sq^56)
            eg_score -= get_2d_val(theta, IDX_PST_EG, pt, 64, sq^56)
            bb &= bb - np.uint64(1)
            
    # Sub modules
    
    # Attacks (Expensive but needed for Safety and Threats)
    white_attacks, black_attacks = _compute_all_attacks(piece_bbs, occupancy_bbs[2])
    
    mks, eks = evaluate_king_safety(piece_bbs, occupancy_bbs, white_attacks, black_attacks, theta)
    mg_score += mks; eg_score += eks
    
    mps, eps = evaluate_pawn_structure(piece_bbs, theta)
    mg_score += mps; eg_score += eps
    
    mpc, epc = evaluate_piece_coordination(piece_bbs, theta)
    mg_score += mpc; eg_score += epc
    
    mmb, emb = evaluate_mobility(piece_bbs, occupancy_bbs, theta)
    mg_score += mmb; eg_score += emb
    
    mth, eth = evaluate_threats(piece_bbs, occupancy_bbs, white_attacks, black_attacks, theta)
    mg_score += mth; eg_score += eth
    
    final_score = (mg_score * phase + eg_score * (MAX_PHASE - phase)) // MAX_PHASE
    
    if phase > INITIATIVE_PHASE_THRESHOLD:
        final_score += get_int(theta, IDX_INITIATIVE_BONUS)
        
    if side_to_move == 0:
        return np.int32(final_score)
    else:
        return np.int32(-final_score)
