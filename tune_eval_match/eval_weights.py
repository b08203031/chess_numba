def apply_param_dict(weights: np.ndarray, params: dict) -> None:
    for name, val in params.items():
        idx = EVAL_PARAM_INDEX.get(name)
        if idx is None:
            raise KeyError(f"Unknown eval param: {name}")
        weights[idx] = int(val)


def params_from_weights(weights: np.ndarray, names=None) -> dict:
    names = names or list(EVAL_PARAM_INDEX.keys())
    return {n: int(weights[EVAL_PARAM_INDEX[n]]) for n in names}


def format_constants_diff(theta_int: dict, constants_module=None) -> str:
    """Format changed parameters relative to ``constants_module`` defaults."""
    base_w = default_eval_weights(constants_module)
    base = params_from_weights(base_w, list(theta_int.keys()))
    lines = []
    for name, new_val in theta_int.items():
        old_val = base[name]
        iv = int(round(float(new_val)))
        if iv != old_val:
            lines.append(f"{name}: {old_val} -> {iv} ({iv - old_val:+d})")
    return "\n".join(lines) if lines else "(no changes vs constants defaults)"
