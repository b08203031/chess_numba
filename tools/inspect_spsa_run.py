#!/usr/bin/env python3
"""
Inspect SPSA Tuning Run & Plot Parameter Trajectories

Analyzes a JSONL log generated by tune_search/search_tuner.py:
1. Console overview: Progress, game balance, checkpoint table, drift z-scores, and tail-averaged parameters.
2. Line charts: Multi-panel plot tracking the evolution of each tuned parameter over iterations,
   including baseline references, latest values, and a normalized relative drift comparison.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tune_search.search_param_registry import get_spec
from tune_search.stats import drift_z


def parse_args():
    parser = argparse.ArgumentParser(
        description="Inspect SPSA tuning progress and plot parameter trajectories."
    )
    parser.add_argument(
        "log_path",
        nargs="?",
        default="lmr_e71_spsa_log.jsonl",
        help="Path to SPSA jsonl log file (default: lmr_e71_spsa_log.jsonl)",
    )
    parser.add_argument(
        "--out",
        "-o",
        default=None,
        help="Output image file path (default: <log_stem>_trajectory.png)",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Display the plot window interactively (plt.show())",
    )
    parser.add_argument(
        "--no-plot",
        action="store_true",
        help="Disable plotting and output console summary only",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=150,
        help="DPI for saved plot image (default: 150)",
    )
    return parser.parse_args()


def plot_trajectories(
    iters,
    initial_params,
    total_planned,
    out_path,
    show=False,
    dpi=150,
):
    try:
        import matplotlib
        if not show:
            matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("\n[Warning] matplotlib is not installed. Skipping plot generation.")
        return

    params = list(iters[0]["params"])
    n_params = len(params)
    iterations = [r["iteration"] for r in iters]
    last_iter = iterations[-1]

    # Subplots: 1 per parameter + 1 for normalized drift comparison
    total_panels = n_params + 1
    ncols = 2
    nrows = (total_panels + ncols - 1) // ncols

    # Try applying clean style if available
    try:
        plt.style.use("seaborn-v0_8-whitegrid")
    except Exception:
        try:
            plt.style.use("seaborn-whitegrid")
        except Exception:
            pass

    fig, axes = plt.subplots(nrows, ncols, figsize=(15, 3.8 * nrows), squeeze=False)

    # 1. Individual parameter subplots
    for idx, p in enumerate(params):
        ax = axes[idx // ncols, idx % ncols]
        spec = get_spec(p)
        baseline = initial_params.get(p, spec.default)
        values = [r["updated_params"][p] for r in iters]
        latest = values[-1]
        delta = latest - baseline

        updates = [float(r["raw_updates"][p]) for r in iters if "raw_updates" in r]
        z = drift_z(updates) if updates else 0.0

        # Trajectory line
        ax.plot(iterations, values, color="#1f77b4", linewidth=1.8, label="Trajectory", zorder=3)

        # Baseline horizontal reference line
        ax.axhline(
            baseline,
            color="#d62728",
            linestyle="--",
            linewidth=1.3,
            alpha=0.8,
            label=f"Baseline ({baseline})",
            zorder=2,
        )

        # Highlight final point
        ax.scatter([last_iter], [latest], color="#1f77b4", s=35, zorder=5)
        ax.annotate(
            f"{latest}",
            (last_iter, latest),
            textcoords="offset points",
            xytext=(-25, 8),
            fontsize=9,
            fontweight="bold",
            color="#0b3c5d",
            bbox=dict(boxstyle="round,pad=0.2", facecolor="white", edgecolor="#1f77b4", alpha=0.85, linewidth=0.7),
            zorder=6,
        )

        # Significance flag in title
        sig_str = ""
        if abs(z) >= 2.58:
            sig_str = " (p < 0.01 ***)"
        elif abs(z) >= 1.96:
            sig_str = " (p < 0.05 **)"
        elif abs(z) >= 1.64:
            sig_str = " (p < 0.10 *)"

        ax.set_title(
            f"{p}\nInitial: {baseline} -> Latest: {latest} (Δ={delta:+d}, z={z:+.2f}){sig_str}",
            fontsize=11,
            fontweight="bold",
        )
        ax.set_xlabel("Iteration", fontsize=9)
        ax.set_ylabel("Value", fontsize=9)
        ax.set_xlim(0, max(total_planned, last_iter + 10))
        ax.legend(loc="upper left", fontsize=8, framealpha=0.85)
        ax.grid(True, linestyle=":", alpha=0.6)

    # 2. Normalized drift macro comparison panel
    comp_ax = axes[(total_panels - 1) // ncols, (total_panels - 1) % ncols]
    try:
        cmap = matplotlib.colormaps.get_cmap("tab10")
    except Exception:
        cmap = plt.cm.get_cmap("tab10")

    for idx, p in enumerate(params):
        spec = get_spec(p)
        baseline = initial_params.get(p, spec.default)
        values = [r["updated_params"][p] for r in iters]
        c_end = float(spec.step)
        norm_values = [(v - baseline) / c_end for v in values]
        comp_ax.plot(
            iterations,
            norm_values,
            label=f"{p} (c={int(c_end)})",
            linewidth=1.6,
            color=cmap(idx % 10),
        )

    comp_ax.axhline(0, color="black", linestyle="-", linewidth=1.0, alpha=0.6)
    comp_ax.axhline(1.0, color="gray", linestyle=":", linewidth=0.8, alpha=0.6)
    comp_ax.axhline(-1.0, color="gray", linestyle=":", linewidth=0.8, alpha=0.6)
    comp_ax.axhline(2.0, color="#d62728", linestyle="--", linewidth=0.8, alpha=0.6)
    comp_ax.axhline(-2.0, color="#d62728", linestyle="--", linewidth=0.8, alpha=0.6)
    comp_ax.set_title(
        "Normalized Parameter Drift (Δ / c_end)\nMacro Comparison Across All Tuning Axes",
        fontsize=11,
        fontweight="bold",
    )
    comp_ax.set_xlabel("Iteration", fontsize=9)
    comp_ax.set_ylabel("Relative Drift (x c_end)", fontsize=9)
    comp_ax.set_xlim(0, max(total_planned, last_iter + 10))
    comp_ax.legend(loc="upper left", ncol=2, fontsize=7.5, framealpha=0.85)
    comp_ax.grid(True, linestyle=":", alpha=0.6)

    # Delete any unused subplot axes
    for idx in range(total_panels, nrows * ncols):
        fig.delaxes(axes[idx // ncols, idx % ncols])

    fig.suptitle(
        f"SPSA Optimization Trajectory — Iteration {last_iter} / {total_planned} "
        f"({last_iter * 14} Games, {last_iter * 7} Pairs)",
        fontsize=14,
        fontweight="bold",
        y=0.995,
    )
    plt.tight_layout(rect=[0, 0, 1, 0.985])

    plt.savefig(out_path, dpi=dpi, bbox_inches="tight")
    print(f"\n[Plot] Saved SPSA trajectory chart to: {out_path}")

    if show:
        plt.show()
    plt.close(fig)


def main():
    args = parse_args()
    log_path = Path(args.log_path)
    if not log_path.exists():
        print(f"[Error] Log file '{log_path}' not found.")
        sys.exit(1)

    lines = [json.loads(line) for line in log_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    iters = [r for r in lines if r.get("event") == "iteration"]

    if not iters:
        print(f"[Error] No iteration events found in '{log_path}'.")
        sys.exit(1)

    # Extract start metadata if present
    start_ev = next((r for r in lines if r.get("event") == "start"), {})
    initial_params = start_ev.get("current_params", {})
    total_planned = start_ev.get("schedule_total_batches", 1000)

    print("=== SPSA Progress Overview ===")
    print(f"Completed iterations: {len(iters)} / {total_planned} ({len(iters)/total_planned*100:.1f}%)")
    print(f"Total games played: {len(iters) * 14} games ({len(iters) * 7} pairs)")
    scores = [float(r["score_plus"]) for r in iters]
    print(f"Average Plus score: {sum(scores)/len(scores):.4f}")
    plus_wins = sum(1 for s in scores if s > 0.5)
    minus_wins = sum(1 for s in scores if s < 0.5)
    draws = sum(1 for s in scores if s == 0.5)
    print(f"Batch distribution: Plus won {plus_wins}, Minus won {minus_wins}, Tied {draws}")

    params = list(iters[0]["params"])
    print("\n=== Checkpoint Trajectory ===")
    header = f"{'Iter':<5} " + " ".join(f"{p[:10]:>10}" for p in params)
    print(header)
    print("-" * len(header))
    indices = list(range(0, len(iters), 100))
    if len(iters) - 1 not in indices:
        indices.append(len(iters) - 1)
    seen = set()
    for i in indices:
        if i < len(iters) and i not in seen:
            seen.add(i)
            r = iters[i]
            vals = " ".join(f"{r['updated_params'][p]:10d}" for p in params)
            print(f"{r['iteration']:<5d} {vals}")

    print("\n=== Parameter Movement & Drift Z-Score ===")
    print(f"{'Parameter':<26} {'Initial':>8} {'Latest':>8} {'Delta':>8} {'c_end':>6} {'Delta/c':>8} {'drift_z':>9}")
    print("-" * 79)
    for p in params:
        spec = get_spec(p)
        baseline = initial_params.get(p, spec.default)
        latest = iters[-1]["updated_params"][p]
        delta = latest - baseline
        updates = [float(r["raw_updates"][p]) for r in iters if "raw_updates" in r]
        z = drift_z(updates) if updates else 0.0
        c_ratio = delta / float(spec.step)
        print(f"{p:<26} {baseline:>8d} {latest:>8d} {delta:>+8d} {spec.step:>6d} {c_ratio:>+8.2f}x {z:>+9.2f}")

    # Generate line charts
    if not args.no_plot:
        out_path = Path(args.out) if args.out else Path(f"{log_path.stem}_trajectory.png")
        plot_trajectories(
            iters=iters,
            initial_params=initial_params,
            total_planned=total_planned,
            out_path=out_path,
            show=args.show,
            dpi=args.dpi,
        )


if __name__ == "__main__":
    main()
